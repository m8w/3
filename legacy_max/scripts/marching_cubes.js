// marching_cubes.js
// Extracts an isosurface from a 3D scalar jit.matrix (float32, planecount 1)
// and emits a triangle vertex list + per-vertex normals for jit.gl.mesh.
//
// Inlets:
//   0 : jit_matrix   3D scalar field
//   0 : threshold <float>   iso value (default 0.5)
//   0 : bang                re-run on last field with current threshold
//
// Outlets:
//   0 : jit_matrix (position)  3 planes float32, dim = 3 * n_triangles
//   1 : jit_matrix (normal)    3 planes float32, dim = 3 * n_triangles
//   2 : n_triangles (int)
//   3 : status/error strings
//
// Uses the standard Paul Bourke MC tables.

autowatch = 1;
inlets  = 1;
outlets = 4;

var THRESHOLD = 0.5;
var LAST_NAME = null;

var POS_MAT = new JitterMatrix(3, "float32", 3, 1);
POS_MAT.name = "fh_mesh_pos";
var NRM_MAT = new JitterMatrix(3, "float32", 3, 1);
NRM_MAT.name = "fh_mesh_nrm";

function threshold(v) { THRESHOLD = parseFloat(v); if (LAST_NAME) run(LAST_NAME); }
function bang()       { if (LAST_NAME) run(LAST_NAME); }
function jit_matrix(name) { LAST_NAME = name; run(name); }

function run(name) {
	var field = new JitterMatrix(name);
	var dim = field.dim;
	if (!dim || dim.length < 3) {
		outlet(3, "error", "field must be 3D");
		return;
	}
	var W = dim[0], H = dim[1], D = dim[2];

	// snapshot the entire field into a typed local array (much faster than getcell)
	var N = W * H * D;
	var vox = new Array(N);
	for (var z = 0; z < D; ++z) {
		for (var y = 0; y < H; ++y) {
			for (var x = 0; x < W; ++x) {
				vox[x + y*W + z*W*H] = field.getcell(x, y, z)[0];
			}
		}
	}

	function get(x, y, z) {
		if (x < 0) x = 0; else if (x >= W) x = W-1;
		if (y < 0) y = 0; else if (y >= H) y = H-1;
		if (z < 0) z = 0; else if (z >= D) z = D-1;
		return vox[x + y*W + z*W*H];
	}
	function grad(x, y, z) {
		return [
			(get(x+1,y,z) - get(x-1,y,z)) * 0.5,
			(get(x,y+1,z) - get(x,y-1,z)) * 0.5,
			(get(x,y,z+1) - get(x,y,z-1)) * 0.5
		];
	}

	var iso = THRESHOLD;
	var verts = [];    // flat: x0,y0,z0, x1,y1,z1, ...
	var norms = [];

	// corner offsets (indexed 0..7 to match Bourke)
	var cornerX = [0,1,1,0, 0,1,1,0];
	var cornerY = [0,0,1,1, 0,0,1,1];
	var cornerZ = [0,0,0,0, 1,1,1,1];
	// edge endpoint indices (edge -> [cornerA, cornerB])
	var edgeVerts = [
		[0,1],[1,2],[2,3],[3,0],
		[4,5],[5,6],[6,7],[7,4],
		[0,4],[1,5],[2,6],[3,7]
	];

	var vertPos = new Array(12);
	var vertNrm = new Array(12);

	for (var z = 0; z < D-1; ++z) {
		for (var y = 0; y < H-1; ++y) {
			for (var x = 0; x < W-1; ++x) {
				var v = [
					get(x  ,y  ,z  ),
					get(x+1,y  ,z  ),
					get(x+1,y+1,z  ),
					get(x  ,y+1,z  ),
					get(x  ,y  ,z+1),
					get(x+1,y  ,z+1),
					get(x+1,y+1,z+1),
					get(x  ,y+1,z+1)
				];
				var ci = 0;
				if (v[0] < iso) ci |= 1;
				if (v[1] < iso) ci |= 2;
				if (v[2] < iso) ci |= 4;
				if (v[3] < iso) ci |= 8;
				if (v[4] < iso) ci |= 16;
				if (v[5] < iso) ci |= 32;
				if (v[6] < iso) ci |= 64;
				if (v[7] < iso) ci |= 128;

				var em = edgeTable[ci];
				if (em === 0) continue;

				// Interpolate along each active edge
				for (var e = 0; e < 12; ++e) {
					if ((em & (1 << e)) === 0) continue;
					var eA = edgeVerts[e][0], eB = edgeVerts[e][1];
					var vA = v[eA], vB = v[eB];
					var denom = vB - vA;
					var t = Math.abs(denom) < 1e-6 ? 0.5 : (iso - vA) / denom;
					var ax = x + cornerX[eA], ay = y + cornerY[eA], az = z + cornerZ[eA];
					var bx = x + cornerX[eB], by = y + cornerY[eB], bz = z + cornerZ[eB];
					vertPos[e] = [
						ax + t * (bx - ax),
						ay + t * (by - ay),
						az + t * (bz - az)
					];
					var gA = grad(ax, ay, az);
					var gB = grad(bx, by, bz);
					var nx = gA[0] + t * (gB[0] - gA[0]);
					var ny = gA[1] + t * (gB[1] - gA[1]);
					var nz = gA[2] + t * (gB[2] - gA[2]);
					var nl = Math.sqrt(nx*nx + ny*ny + nz*nz) + 1e-8;
					// negate: field grows *inside* the mass, gradient points inward
					vertNrm[e] = [-nx/nl, -ny/nl, -nz/nl];
				}

				var tri = triTable[ci];
				for (var t2 = 0; tri[t2] !== -1 && t2 < 15; t2 += 3) {
					var e0 = tri[t2], e1 = tri[t2+1], e2 = tri[t2+2];
					var p0 = vertPos[e0], p1 = vertPos[e1], p2 = vertPos[e2];
					var n0 = vertNrm[e0], n1 = vertNrm[e1], n2 = vertNrm[e2];
					// normalize into [-1, +1] world coords
					verts.push(
						(p0[0]/W - 0.5) * 2, (p0[1]/H - 0.5) * 2, (p0[2]/D - 0.5) * 2,
						(p1[0]/W - 0.5) * 2, (p1[1]/H - 0.5) * 2, (p1[2]/D - 0.5) * 2,
						(p2[0]/W - 0.5) * 2, (p2[1]/H - 0.5) * 2, (p2[2]/D - 0.5) * 2
					);
					norms.push(n0[0], n0[1], n0[2],
					           n1[0], n1[1], n1[2],
					           n2[0], n2[1], n2[2]);
				}
			}
		}
	}

	var nTri = verts.length / 9;
	if (nTri === 0) {
		outlet(2, 0);
		return;
	}

	POS_MAT.dim = [nTri * 3, 1];
	NRM_MAT.dim = [nTri * 3, 1];
	for (var k = 0; k < nTri * 3; ++k) {
		POS_MAT.setcell(k, 0, "val",
			verts[k*3], verts[k*3+1], verts[k*3+2]);
		NRM_MAT.setcell(k, 0, "val",
			norms[k*3], norms[k*3+1], norms[k*3+2]);
	}
	outlet(0, "jit_matrix", POS_MAT.name);
	outlet(1, "jit_matrix", NRM_MAT.name);
	outlet(2, nTri);
}

